# Режимы доступа

# attribute(без одного или двух подчёркиваний вначале) - публичное свойство public
# _attribute(с одним подчёркиванием) - режим доступа protected
# __attribute(с двумя подчёркиваниями) - режим доступа private

class Point:
    def __init__(self, x, y):
        self.x = x
        self.y = y




