# Множества(set) - это не упорядоченная коллекция уникальных элементов

a ={1,2,3,4,5,6,7,8,9}
print(a)
print(type(a))

a ={1,2,3,4,5,6,7,8,9,2,3}
print(a)
print(type(a))

# Можно использовать в множествах
# числа
# булевые значения
# строки
# кортежи

#  Нельзя использовать
# списки
# словари
# другие множества

print(set("python"))

# Множества убирают повторяющиеся элементы


